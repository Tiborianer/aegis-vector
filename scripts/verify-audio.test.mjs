import { describe, it, expect, vi } from 'vitest';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { REQUIRED_MISSION_SCORE_TRACKS, verifyAudio } from './verify-audio.mjs';

const BASE_FILES = [
  'menu.mp3', 'hangar.mp3', 'mission-coastal.mp3', 'mission-minefield.mp3',
  'mission-fortress.mp3', 'boss.mp3', 'boss-mech-tyrants.mp3',
  'victory-coastal.mp3', 'victory-minefield.mp3', 'victory-fortress.mp3',
  'victory-campaign.mp3', 'defeat-signal.mp3', 'defeat-debrief.mp3',
  'ending/homeward-vector-v1.mp3',
];
// Synthetic header fixtures only: these tests do not claim audio decode/audition.
const fixtureBytes = (name) => Buffer.concat([Buffer.from(`ID3${name}`), Buffer.alloc(1200)]);
const integrity = (bytes) => ({ bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });

async function fixture(reviewed = false) {
  const root = await mkdtemp(join(tmpdir(), 'aegis-score-verifier-'));
  const put = async (file, bytes) => {
    await mkdir(join(root, file, '..'), { recursive: true });
    await writeFile(join(root, file), bytes);
  };
  for (const file of BASE_FILES) await put(`audio/${file}`, fixtureBytes(file));
  const missionScores = {};
  for (const track of REQUIRED_MISSION_SCORE_TRACKS) {
    const file = `audio/missions/${track}-v1.mp3`;
    const bytes = fixtureBytes(track);
    missionScores[track] = { status: reviewed ? 'reviewed' : 'awaiting-elevenlabs', file: reviewed ? file : null, fallback: 'audio/mission-coastal.mp3', ...integrity(bytes) };
    if (reviewed) await put(file, bytes);
  }
  return { root, put, options: { missionScores, storyScores: {}, warn: vi.fn() } };
}

describe('mission soundtrack release verification', () => {
  it('imports without executing the CLI or reading production audio', () => {
    const moduleUrl = new URL('./verify-audio.mjs', import.meta.url);
    const result = spawnSync(process.execPath, ['--input-type=module', '-e', `await import(${JSON.stringify(moduleUrl.href)})`], { encoding: 'utf8' });
    expect(result.status).toBe(0);
    expect(result.stdout).toBe('');
    expect(result.stderr).toBe('');
  });

  it('permits the documented local fallback but never calls it release-ready', async () => {
    const { root, options } = await fixture();
    expect(await verifyAudio(root, options)).toMatchObject({ distinctMissionFiles: 3 });
    expect(options.warn).toHaveBeenCalledTimes(REQUIRED_MISSION_SCORE_TRACKS.length);
    await expect(verifyAudio(root, { ...options, requireMissionScores: true })).rejects.toThrow('still pending');
  });

  it('requires all six manifest entries even in fallback builds', async () => {
    const { root, options } = await fixture(true);
    for (const track of REQUIRED_MISSION_SCORE_TRACKS) {
      const scores = { ...options.missionScores };
      delete scores[track];
      for (const requireMissionScores of [false, true]) {
        await expect(verifyAudio(root, { ...options, missionScores: scores, requireMissionScores })).rejects.toThrow(`Missing mission score manifest entry: ${track}`);
      }
    }
  });

  it('rejects misspelled tracks and invalid status values', async () => {
    const { root, options } = await fixture(true);
    await expect(verifyAudio(root, { ...options, missionScores: { ...options.missionScores, 'mission-typo': {} } })).rejects.toThrow('Unknown mission score');
    options.missionScores['mission-stormbreak'].status = 'reviewd';
    await expect(verifyAudio(root, options)).rejects.toThrow('Invalid mission score status');
  });

  it('requires review, not just generated bytes', async () => {
    const { root, options } = await fixture(true);
    options.missionScores['mission-stormbreak'].status = 'generated';
    await expect(verifyAudio(root, { ...options, requireMissionScores: true })).rejects.toThrow('still pending');
  });

  it('accepts nine distinct mission files only after all six additions are reviewed', async () => {
    const { root, options } = await fixture(true);
    const result = await verifyAudio(root, { ...options, requireMissionScores: true });
    expect(result.distinctMissionFiles).toBe(9);
    expect(result.files).toHaveLength(20);
    expect(options.warn).not.toHaveBeenCalled();
  });

  it('keeps Aurora playable on its declared bed but blocks release until its own score is reviewed', async () => {
    const { root, options } = await fixture(true);
    options.missionScores['mission-aurora'] = {
      file: null,
      fallback: 'audio/mission-coastal.mp3',
      status: 'awaiting-elevenlabs',
      reviewPending: 'Dedicated Aurora score still requires generation and owner listening approval.',
    };
    expect(await verifyAudio(root, options)).toMatchObject({ distinctMissionFiles: 8 });
    expect(options.warn).toHaveBeenCalledTimes(1);
    expect(options.warn).toHaveBeenCalledWith(expect.stringContaining('mission-aurora: generation/listening review pending'));
    await expect(verifyAudio(root, { ...options, requireMissionScores: true })).rejects.toThrow('mission-aurora: distinct ElevenLabs mission score generation/listening review is still pending.');
    options.missionScores['mission-aurora'].status = 'generated';
    await expect(verifyAudio(root, { ...options, requireMissionScores: true })).rejects.toThrow('mission-aurora: distinct ElevenLabs mission score generation/listening review is still pending.');
  });

  it('rejects the same file assigned to two mission identities', async () => {
    const { root, options } = await fixture(true);
    options.missionScores['mission-graveyard'] = { ...options.missionScores['mission-stormbreak'] };
    await expect(verifyAudio(root, options)).rejects.toThrow('Duplicate mission score path');
  });

  it('rejects identical music copied to different names, including original-score copies', async () => {
    for (const duplicateOf of ['mission-coastal.mp3', 'mission-stormbreak']) {
      const { root, put, options } = await fixture(true);
      const score = options.missionScores['mission-graveyard'];
      const bytes = fixtureBytes(duplicateOf);
      Object.assign(score, integrity(bytes));
      await put(score.file, bytes);
      await expect(verifyAudio(root, options)).rejects.toThrow('each mission needs a distinct score');
    }
  });

  it('retains byte-count and hash integrity enforcement', async () => {
    const { root, options } = await fixture(true);
    options.missionScores['mission-last-light'].sha256 = '0'.repeat(64);
    await expect(verifyAudio(root, options)).rejects.toThrow('Mission score integrity mismatch');
  });

  it('rejects empty, malformed and high-bit forged MP3 headers', async () => {
    const { root, put, options } = await fixture();
    const forged = fixtureBytes('forged');
    forged[0] |= 0x80;
    for (const bytes of [Buffer.alloc(0), Buffer.alloc(1200), forged]) {
      await put('audio/menu.mp3', bytes);
      await expect(verifyAudio(root, options)).rejects.toThrow('MP3 header');
    }
  });
});
